-- Persistent OCR staging/draft records. These survive refresh, logout, and app restart.
create table if not exists public.ppmp_ocr_drafts (
  id bigint generated by default as identity primary key,
  upload_token text,
  temp_code text unique,
  ppmp_category text not null,
  fields_json text not null default '{}',
  confidence_json text not null default '{}',
  average_confidence double precision default 0,
  source_filename text,
  raw_ocr_text text,
  extraction_method text,
  status text not null default 'NEEDS_REVIEW',
  reviewed boolean not null default false,
  reviewed_by text,
  reviewed_at text,
  converted boolean not null default false,
  official_ppmp_id bigint references public.ppmp(id) on delete set null,
  converted_at text,
  created_by text,
  created_at text,
  updated_at text
);
create index if not exists idx_ppmp_ocr_drafts_category_status on public.ppmp_ocr_drafts(ppmp_category, status);
create unique index if not exists idx_ppmp_ocr_drafts_official_ppmp on public.ppmp_ocr_drafts(official_ppmp_id) where official_ppmp_id is not null;
