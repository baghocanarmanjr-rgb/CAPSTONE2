-- PSMS Supabase/PostgreSQL schema
-- Safe to run repeatedly with: supabase db reset, psql, or the application's init_db().

create table if not exists public.ppmp (
  id bigint generated by default as identity primary key,
  no text unique,
  type text,
  office text,
  year integer,
  status text,
  created_at text,
  items text,
  total double precision default 0,
  source_dataset_record_id bigint,
  anomaly_score double precision,
  anomaly_label text,
  anomaly_reasons text,
  anomaly_review_status text,
  anomaly_model_version text
);

create table if not exists public.app_plan (
  id bigint generated by default as identity primary key,
  no text unique,
  ppmp_id bigint references public.ppmp(id) on delete set null,
  year integer,
  office text,
  status text,
  created_at text,
  total double precision default 0,
  items text
);

create table if not exists public.pr (
  id bigint generated by default as identity primary key,
  no text unique,
  app_id bigint references public.app_plan(id) on delete set null,
  ppmp_id bigint references public.ppmp(id) on delete set null,
  office text,
  purpose text,
  status text,
  created_at text,
  items text,
  total double precision default 0
);

create table if not exists public.aoq (
  id bigint generated by default as identity primary key,
  no text unique,
  pr_id bigint references public.pr(id) on delete set null,
  status text,
  created_at text,
  suppliers text,
  winner text,
  winning_amount double precision default 0,
  winning_offer text,
  ocr_filename text,
  ocr_text text,
  stored_filename text,
  source_type text,
  extraction_method text,
  extraction_profile text,
  extraction_warnings text
);

create table if not exists public.po (
  id bigint generated by default as identity primary key,
  no text unique,
  aoq_id bigint references public.aoq(id) on delete set null,
  supplier text,
  status text,
  created_at text,
  items text,
  total double precision default 0
);

create table if not exists public.nlp (
  id bigint generated by default as identity primary key,
  no text unique,
  po_id bigint references public.po(id) on delete set null,
  result text,
  confidence double precision,
  staff_decision text,
  remarks text,
  created_at text,
  details text,
  status text
);

create table if not exists public.iar (
  id bigint generated by default as identity primary key,
  no text unique,
  po_id bigint references public.po(id) on delete set null,
  status text,
  created_at text,
  items text
);

create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  item text,
  description text,
  category text,
  qty double precision default 0,
  unit text,
  source_po text,
  status text,
  created_at text,
  unit_cost double precision default 0,
  source_dataset_record_id bigint,
  item_code text unique,
  anomaly_score double precision,
  anomaly_label text,
  anomaly_reasons text,
  anomaly_model_version text
);

create table if not exists public.ris_ics (
  id bigint generated by default as identity primary key,
  no text unique,
  type text,
  office text,
  status text,
  created_at text,
  items text
);

create table if not exists public.audit_trail (
  id bigint generated by default as identity primary key,
  dt text,
  "user" text,
  action text,
  module text,
  ref text,
  details text
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text unique not null,
  password text not null,
  role text not null default 'Admin'
);

create table if not exists public.identifier_sequence (
  sequence_key text primary key,
  last_number bigint not null default 0
);

create table if not exists public.inventory_transactions (
  id bigint generated by default as identity primary key,
  inventory_id bigint references public.inventory(id) on delete set null,
  document_no text,
  transaction_type text,
  qty double precision,
  unit text,
  office text,
  created_at text,
  created_by text
);

create table if not exists public.dataset_config (
  id integer primary key check (id = 1),
  filename text,
  stored_path text,
  file_hash text,
  modified_ts double precision,
  last_synced text,
  sheet_count integer default 0,
  row_count integer default 0,
  model_version text,
  status text,
  last_error text
);

create table if not exists public.dataset_sheets (
  id bigint generated by default as identity primary key,
  sheet_name text unique,
  header_row integer,
  row_count integer,
  columns_json text,
  active integer default 1,
  updated_at text
);

create table if not exists public.dataset_records (
  id bigint generated by default as identity primary key,
  record_key text unique,
  sheet_name text,
  source_row integer,
  article text,
  description text,
  property_number text,
  unit text,
  unit_value double precision,
  balance_qty double precision,
  on_hand_qty double precision,
  shortage_qty double precision,
  shortage_value double precision,
  remarks text,
  office text,
  accountable_person text,
  raw_data text,
  normalized_data text,
  anomaly_score double precision,
  anomaly_label text,
  anomaly_reasons text,
  review_status text,
  active integer default 1,
  imported_at text,
  updated_at text
);

create index if not exists idx_nlp_no on public.nlp(no);
create index if not exists idx_inventory_item_code on public.inventory(item_code);
create index if not exists idx_dataset_records_sheet on public.dataset_records(sheet_name, active);
create index if not exists idx_dataset_records_description on public.dataset_records(description);
create index if not exists idx_dataset_records_property on public.dataset_records(property_number);
create index if not exists idx_inventory_status on public.inventory(status);
create index if not exists idx_audit_id_desc on public.audit_trail(id desc);
